/**
 * Build the toggle button for a single block.
 *
 * @param {Object} labels play/pause/resume button text.
 * @return {HTMLButtonElement}
 */
function createButton(labels) {
    var button = document.createElement('button');
    button.type = 'button';
    button.className = 'btn btn-secondary btn-sm coursegenerator-tts-btn mt-2';
    button.textContent = labels.play;
    return button;
}

/**
 * Wire up click handling for a button so it plays, pauses and resumes the
 * speech synthesis for the given text.
 *
 * @param {HTMLButtonElement} button
 * @param {HTMLElement} textEl element whose text content gets read aloud.
 * @param {Object} labels play/pause/resume button text.
 */
function wireButton(button, textEl, labels) {
    var synth = window.speechSynthesis;
    var state = 'idle';
    var utterance = null;

    var reset = function() {
        state = 'idle';
        button.textContent = labels.play;
    };

    button.addEventListener('click', function() {
        if (state === 'idle') {
            // Stop any other block that might be reading, to avoid overlap.
            synth.cancel();
            utterance = new SpeechSynthesisUtterance(textEl.textContent.trim());
            utterance.lang = document.documentElement.lang || 'es-ES';
            utterance.addEventListener('end', reset);
            utterance.addEventListener('error', reset);
            synth.speak(utterance);
            state = 'playing';
            button.textContent = labels.pause;
        } else if (state === 'playing') {
            synth.pause();
            state = 'paused';
            button.textContent = labels.resume;
        } else {
            synth.resume();
            state = 'playing';
            button.textContent = labels.pause;
        }
    });
}

export const init = (headings, labels) => {
    if (!('speechSynthesis' in window)) {
        return;
    }

    document.querySelectorAll('h3').forEach((heading) => {
        var text = heading.textContent.trim();
        if (text !== headings.content && text !== headings.question) {
            return;
        }
        if (heading.dataset.cgTtsReady) {
            return;
        }
        heading.dataset.cgTtsReady = '1';

        var textEl = heading.nextElementSibling;
        if (!textEl) {
            return;
        }

        var button = createButton(labels);
        textEl.insertAdjacentElement('afterend', button);
        wireButton(button, textEl, labels);
    });
};
